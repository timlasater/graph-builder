import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('refresh linked source updates plotted values and embedded exports, then Undo restores the data', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  page.once('dialog', (dialog) => dialog.accept())
  await page.locator('input[type="file"][accept*=".csv"]').first().setInputFiles({ name: 'results.csv', mimeType: 'text/csv', buffer: Buffer.from('Time,Value\n1,10\n2,20\n') })
  await page.getByRole('button', { name: 'Import selected data' }).click()
  await expect.poll(() => page.locator('.plotly-chart').evaluate((el) => (el as HTMLElement & { data?: { y?: number[] }[] }).data?.[0]?.y)).toEqual([10, 20])
  await page.getByRole('button', { name: 'Projects & export' }).click()
  await page.getByLabel('Data in saved file').selectOption('linked')
  const linkedDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download project' }).click()
  await linkedDownload
  await expect(page.getByRole('button', { name: 'Refresh linked source' })).toBeVisible()
  page.once('dialog', (dialog) => dialog.accept())
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Refresh linked source' }).click()
  await (await chooser).setFiles({ name: 'results.csv', mimeType: 'text/csv', buffer: Buffer.from('Time,Value\n1,100\n2,200\n3,300\n') })
  await expect(page.getByRole('status').filter({ hasText: 'Linked source refreshed: 3 rows' })).toBeVisible()
  await expect(page.locator('.project-section .setting-help')).toHaveCSS('font-size', '9px')
  await page.screenshot({ path: 'test-results/linked-source-refresh.png' })
  await page.getByRole('button', { name: 'Close projects' }).click()
  await expect.poll(() => page.locator('.plotly-chart').evaluate((el) => (el as HTMLElement & { data?: { y?: number[] }[] }).data?.[0]?.y)).toEqual([100, 200, 300])
  await page.getByTitle('Undo (Ctrl+Z)', { exact: true }).click()
  await expect.poll(() => page.locator('.plotly-chart').evaluate((el) => (el as HTMLElement & { data?: { y?: number[] }[] }).data?.[0]?.y)).toEqual([10, 20])
  await page.getByTitle('Redo (Ctrl+Y)', { exact: true }).click()
  await expect.poll(() => page.locator('.plotly-chart').evaluate((el) => (el as HTMLElement & { data?: { y?: number[] }[] }).data?.[0]?.y)).toEqual([100, 200, 300])
  await page.getByRole('button', { name: 'Projects & export' }).click()
  await page.getByLabel('Data in saved file').selectOption('embedded')
  const embeddedDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download project' }).click()
  const exported = JSON.parse(await readFile(await (await embeddedDownload).path(), 'utf8'))
  expect(exported.data.dataset.rows).toHaveLength(3)
  expect(Object.values(exported.data.dataset.rows[2].values)).toContain(300)
})
